def compare_keys(dict_a, dict_b, prefix=""):
    diffs = []
    keys_a = set(dict_a.keys())
    keys_b = set(dict_b.keys())
    
    for k in keys_a - keys_b:
        diffs.append(f"Missing in target: {prefix}{k}")
    for k in keys_b - keys_a:
        diffs.append(f"Extra in target: {prefix}{k}")
    for k in keys_a & keys_b:
        if isinstance(dict_a[k], dict) and isinstance(dict_b[k], dict):
            diffs.extend(compare_keys(dict_a[k], dict_b[k], prefix=f"{prefix}{k}."))
        elif isinstance(dict_a[k], dict) != isinstance(dict_b[k], dict):
            diffs.append(f"Type mismatch at: {prefix}{k}")
    return diffs

def count_keys(d):
    count = 0
    for k, v in d.items():
        if isinstance(v, dict):
            count += count_keys(v)
        else:
            count += 1
    return count

